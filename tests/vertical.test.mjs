import {prepareTestAccounts, testCredentials} from './test-accounts.mjs';
import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,readdirSync,mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {sqliteAdapter} from '../scripts/sqlite-adapter.mjs';
import {handleApi} from '../lib/api.mjs';
import {applySeed} from '../lib/seed.mjs';

test('vertical: sessions, persistence, two owners and idempotent atomic requests',async()=>{
  const path=join(mkdtempSync(join(tmpdir(),'orbit-test-')),'db.sqlite');
  let db=sqliteAdapter(path);
  for(const file of readdirSync('drizzle').filter(x=>x.endsWith('.sql'))) db.sqlite.exec(readFileSync('drizzle/'+file,'utf8'));
  await prepareTestAccounts(db);
  const call=async(path,{method='GET',body,cookie,origin='http://localhost:5173'}={})=>{
    const headers={origin,'content-type':'application/json'};if(cookie)headers.cookie=cookie;
    const response=await handleApi(new Request('http://localhost:5173/api'+path,{method,headers,...(body!==undefined?{body:JSON.stringify(body)}:{})}),db);
    return {response,status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
  };
  assert.equal((await call('/session')).status,401);
  const unknown=await call('/login',{method:'POST',body:{login:'unknown',password:'bad'}});
  const wrong=await call('/login',{method:'POST',body:{login:'alina',password:'bad'}});
  assert.equal(unknown.status,401);assert.deepEqual(unknown.data,wrong.data);
  const a=await call('/login',{method:'POST',body:testCredentials('alina')});
  assert.equal(a.status,200);assert.equal(a.data.student.firstName,'Алина');
  assert.match(a.response.headers.get('set-cookie'),/HttpOnly; SameSite=Lax/);
  assert.equal(JSON.stringify(a.data).includes('password'),false);
  assert.equal((await call('/requests',{method:'POST',cookie:a.cookie,body:{}})).status,422);
  assert.equal((await call('/requests',{method:'POST',cookie:a.cookie,origin:'https://attacker.test',body:{}})).status,403);
  const payload={type:'Вопрос по учёбе',message:'Вымышленный вопрос для проверки прототипа.',idempotencyKey:crypto.randomUUID(),studentId:'student-mark'};
  const created=await call('/requests',{method:'POST',cookie:a.cookie,body:payload});
  assert.equal(created.status,201);const id=created.data.request.id;
  const replay=await call('/requests',{method:'POST',cookie:a.cookie,body:payload});
  assert.equal(replay.data.request.id,id);assert.equal(replay.data.request.history.length,1);
  assert.equal((await call('/requests/'+id,{cookie:a.cookie})).data.request.message,payload.message);
  await applySeed(db);await applySeed(db);
  assert.equal(db.sqlite.prepare('SELECT count(*) AS n FROM students').get().n,2);
  assert.equal(db.sqlite.prepare('SELECT count(*) AS n FROM requests WHERE id=?').get(id).n,1);
  assert.equal(db.sqlite.prepare('SELECT student_id FROM requests WHERE id=?').get(id).student_id,'student-alina');
  assert.equal((await call('/logout',{method:'POST',cookie:a.cookie})).status,200);
  assert.equal((await call('/session',{cookie:a.cookie})).status,401);
  const b=await call('/login',{method:'POST',body:testCredentials('mark')});
  assert.equal(b.data.student.firstName,'Марк');
  assert.equal((await call('/requests/'+id,{cookie:b.cookie})).status,404);
  assert.equal((await call('/requests',{cookie:b.cookie})).data.requests.some(x=>x.id===id),false);
  db.sqlite.close();db=sqliteAdapter(path);
  const again=await call('/login',{method:'POST',body:testCredentials('alina')});
  assert.equal((await call('/requests/'+id,{cookie:again.cookie})).status,200);
  const rows=db.sqlite.prepare('SELECT password_hash FROM credentials').all();assert.ok(rows.every(x=>x.password_hash.startsWith('pbkdf2$')&&!x.password_hash.includes('Orbit')));
  db.sqlite.close();
});
