import re as _re
stamp='2026-11-21'
def begin(kicker):
    global stamp
    found=_re.search(r'\d{4}-\d{2}-\d{2}',str(kicker))
    if found:stamp=found.group(0)
    global page
    if page:c.showPage()
    page+=1
    c.setFillColor(white);c.rect(0,0,W,H,fill=1,stroke=0)
    c.setFont('Orbit',8);c.setFillColor(PURPLE);c.drawString(42,H-34,'ОРБИТА / '+clean(kicker).upper())
    c.setStrokeColor(LINE);c.line(42,H-47,W-42,H-47)
    c.setFillColor(MUTED);c.setFont('Orbit',7)
    c.drawString(42,26,'Конкурсный концепт для РЭУ. Учебные данные вымышлены. / '+stamp)
    c.drawRightString(W-42,26,str(page))
def photo(name,x,top,width,max_height):
    path=shots/name
    if not path.exists():raise RuntimeError('Evidence screenshot missing: '+str(path))
    image=ImageReader(str(path));iw,ih=image.getSize();scale=min(width/iw,max_height/ih)
    dw,dh=iw*scale,ih*scale
    c.setFillColor(BG);c.roundRect(x-2,top-dh-2,dw+4,dh+4,8,fill=1,stroke=0)
    c.drawImage(image,x,top-dh,dw,dh,preserveAspectRatio=True,mask='auto')
    return top-dh
def table(rows,widths,y):
    style=ParagraphStyle('cell',fontName='Orbit',fontSize=8.6,leading=12.6,textColor=INK)
    body=[[Paragraph(html.escape(clean(v)).replace('\n','<br/>'),style) for v in row] for row in rows]
    item=Table(body,colWidths=widths,hAlign='LEFT')
    item.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),BG),('VALIGN',(0,0),(-1,-1),'TOP'),('BOTTOMPADDING',(0,0),(-1,-1),9),('TOPPADDING',(0,0),(-1,-1),9),('LEFTPADDING',(0,0),(-1,-1),9),('RIGHTPADDING',(0,0),(-1,-1),9),('LINEBELOW',(0,0),(-1,-1),.5,LINE)]))
    _,height=item.wrap(W-84,H)
    if y-height<48:raise RuntimeError(f'Page {page}: table overflow {height}')
    item.drawOn(c,42,y-height);return y-height-16
def url(label,target,y):
    y2=p(label,y,9.2,color=PURPLE,gap=9)
    c.linkURL(target,(42,y2+6,W-42,y),relative=0,thickness=0)
    return y2


