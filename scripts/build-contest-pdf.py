def photo(name,x,top,width,max_height):
    path=shots/name
    if not path.exists():raise RuntimeError('Evidence screenshot missing: '+str(path))
    image=ImageReader(str(path));iw,ih=image.getSize();scale=min(width/iw,max_height/ih)
    dw,dh=iw*scale,ih*scale
    c.setFillColor(BG);c.roundRect(x-2,top-dh-2,dw+4,dh+4,8,fill=1,stroke=0)
    c.drawImage(image,x,top-dh,dw,dh,preserveAspectRatio=True,mask='auto')
    return top-dh
def table(rows,widths,y):
    style=ParagraphStyle('cell',fontName='Orbit',fontSize=8.6,leading=12.6,textColor=INK)
    body=[[Paragraph(html.escape(clean(v)).replace('\n','<br/>'),style) for v in row] for row in rows]
    item=Table(body,colWidths=widths,hAlign='LEFT')
    item.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),HexColor('#E8EFEA')),('VALIGN',(0,0),(-1,-1),'TOP'),('BOTTOMPADDING',(0,0),(-1,-1),9),('TOPPADDING',(0,0),(-1,-1),9),('LEFTPADDING',(0,0),(-1,-1),9),('RIGHTPADDING',(0,0),(-1,-1),9),('LINEBELOW',(0,0),(-1,-1),.5,LINE)]))
    _,height=item.wrap(W-84,H)
    if y-height<48:raise RuntimeError(f'Page {page}: table overflow {height}')
    item.drawOn(c,42,y-height);return y-height-16
