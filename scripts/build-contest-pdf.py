def clean(text):return str(text).replace('—','-').replace('–','-').replace('\u2011','-')
def p(text,y,size=10,width=None,x=42,color=INK,gap=10):
    text=html.escape(clean(text)).replace('\n','<br/>')
    style=ParagraphStyle('p',fontName='Orbit',fontSize=size,leading=size*1.48,textColor=color,spaceAfter=0)
    item=Paragraph(text,style);_,height=item.wrap(width or W-84,H)
    if y-height<48:raise RuntimeError(f'Page {page} overflow: {text[:60]}')
    item.drawOn(c,x,y-height)
    return y-height-gap
def title(text,y=755):return p(text,y,25,gap=20)
def sub(text,y):return p(text,y,13,color=PURPLE,gap=9)
